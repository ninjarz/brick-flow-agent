import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('brick-flow-agent:locale:v1', 'zh-CN'))
  await page.goto('./')
  page.on('dialog', dialog => dialog.accept())
  await page.getByLabel('作品与素材', { exact: true }).click()
  await page.getByRole('button', { name: '世界场景', exact: true }).click()
  await page.locator('.scenario-card').first().getByRole('button', { name: '开始场景', exact: true }).click()
  await page.locator('.world-story-dock').getByLabel('折叠', { exact: true }).click()
  await page.locator('.world-story-dock').getByLabel('世界酒馆', { exact: true }).click()
})

test('tavern defaults to current objectives and offers a route to story dialogue', async ({ page }, testInfo) => {
  const tavern = page.locator('.tavern-modal')
  await expect(tavern.getByRole('button', { name: '当前剧情', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(tavern.locator('.tavern-quest li.active').first()).toBeVisible()
  await expect(tavern.locator('.tavern-quest li.locked')).toHaveCount(0)
  await expect(tavern.getByRole('button', { name: '新建流程', exact: true })).toHaveCount(0)
  await expect(tavern.getByRole('button', { name: '删除', exact: true })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('tavern-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('tavern-mobile.png') })
  expect(await tavern.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await tavern.getByRole('button', { name: '进入剧情对话', exact: true }).click()
  await expect(tavern).toHaveCount(0)
  await expect(page.locator('.world-story-composer')).toBeVisible()
})

test('character selection opens its profile and history has its own view', async ({ page }) => {
  const tavern = page.locator('.tavern-modal')
  await tavern.locator('.tavern-characters > button').first().click()
  await expect(tavern.getByRole('button', { name: '角色档案', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(tavern.locator('.tavern-memory-panel')).toBeVisible()
  await expect(tavern.locator('.tavern-quest')).toHaveCount(0)
  await tavern.getByRole('button', { name: '事件记录', exact: true }).click()
  await expect(tavern.locator('.tavern-chronicle')).toBeVisible()
  await expect(tavern.locator('.tavern-memory-panel')).toHaveCount(0)
})

test('authoring keeps draft controls reachable and protects an open edit session', async ({ page }) => {
  const tavern = page.locator('.tavern-modal')
  await tavern.getByRole('button', { name: '编辑剧情', exact: true }).click()
  await tavern.getByRole('button', { name: '新建流程', exact: true }).click()
  await expect(tavern.locator('.scenario-edit-session-bar')).toBeVisible()
  await tavern.getByLabel('流程名称', { exact: true }).fill('保留的剧情草稿')
  await tavern.getByRole('button', { name: '当前剧情', exact: true }).click()
  await expect(tavern.locator('.scenario-edit-session-bar')).toHaveCount(0)
  await tavern.getByRole('button', { name: '编辑剧情', exact: true }).click()
  await expect(tavern.locator('.scenario-edit-session-bar')).toBeVisible()
  await expect(tavern.getByLabel('流程名称', { exact: true })).toHaveValue('保留的剧情草稿')
  await tavern.locator('.scenario-edit-session-bar').getByRole('button', { name: '取消', exact: true }).click()
  await expect(tavern.getByRole('button', { name: '当前剧情', exact: true })).toBeEnabled()
})
